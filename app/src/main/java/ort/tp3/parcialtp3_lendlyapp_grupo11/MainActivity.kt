                }
            }
        }
    }
}

@Composable
fun Greeting(name: String, modifier: Modifier = Modifier) {
    Image(
        painter = painterResource(id = R.drawable.logo),
        contentDescription = "Logo",
        modifier = Modifier.fillMaxSize()
    )
    Text(
        text = "Hello $name!",
        modifier = modifier
    )
}

